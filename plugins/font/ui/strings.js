/**
 * The wording for a failure the native half reported as a token. The token is a fact about what
 * happened, and the sentence around it belongs to the interface's language.
 */
export function errorText(token, locale) {
  const [kind = "", detail = ""] = String(token ?? "").split(":", 2);
  if (kind === "font-too-large") return say("errorTooLarge", { limit: detail || "?" });
  if (kind === "font-truncated") return say("errorTruncated");
  if (kind === "font-unknown" || kind === "font-container-unsupported")
    return say("errorUnsupported");
  if (kind === "font-collection-count") return say("errorCollection");
  if (kind === "font-face-index") return say("errorNoFace");
  if (kind === "font-session-expired") return say("errorExpired");
  if (kind.startsWith("font-broken")) return say("errorBroken");
  // Anything else is the host's own wording, in whatever language it was written in.
  const text = String(token ?? "").trim();
  return text || say("missing");
}

